#!/usr/bin/env sh
# Generate the judgment plugin's reference pages from the crate's own
# documentation, so the plugin ships the pages its skills read and they
# cannot drift from the crate. Each page loses its frontmatter, gains a
# header naming its source, and has every relative link rewritten to an
# absolute URL on the repository's default branch, since the plugin is read
# outside this checkout. The rewrite is gen-plugin-format.sh's, with each
# page's own directory as the base of a sibling link.
#
#   scripts/gen-plugin-judgment.sh            write plugins/judgment/skills/*/references/
#   scripts/gen-plugin-judgment.sh --check    exit 1 when a committed page is stale
#
# POSIX sh and sed only.
set -eu

root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$root"
base=https://github.com/chussenot/judgment/blob/main
skills=plugins/judgment/skills

# skill:page, one per line: the docs page each skill ships under references/.
pages="
judgment:docs/reference/crate.md
judgment:docs/concepts/how-judgment-works.md
judgment:docs/guides/configure-a-backend.md
judgment:docs/guides/patterns.md
judgment:docs/start/first-decision-rust.md
judgment-test:docs/guides/record-replay-and-test.md
judgment-observe:docs/guides/export-to-opentelemetry.md
judgment-observe:docs/guides/bound-a-stream.md
"

mode=write
if [ "${1:-}" = "--check" ]; then
  mode=check
fi

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
stale=0
for entry in $pages; do
  skill=${entry%%:*}
  src=${entry#*:}
  dir=$(dirname "$src")         # docs/guides
  sub=${dir#docs/}              # guides
  out="$skills/$skill/references/$(basename "$src")"
  {
    printf '<!-- Generated by scripts/gen-plugin-judgment.sh from %s. Do not edit; edit the page and run the script. -->\n\n' "$src"
    awk 'NR == 1 && $0 == "---" { infm = 1; next } infm && $0 == "---" { infm = 0; next } !infm' "$src" \
      | sed -E \
          -e "s#\]\(\.\./\.\./([^)#]+)#](${base}/\1#g" \
          -e "s#\]\(\.\./([^)#]+)#](${base}/docs/\1#g" \
          -e "s#\]\(([A-Za-z0-9_-]+\.md)#](${base}/docs/${sub}/\1#g"
  } > "$tmp"
  if [ "$mode" = check ]; then
    if ! cmp -s "$tmp" "$out"; then
      echo "$out is stale: run scripts/gen-plugin-judgment.sh and commit the result" >&2
      stale=1
    fi
  else
    mkdir -p "$(dirname "$out")"
    cmp -s "$tmp" "$out" 2>/dev/null || { cp "$tmp" "$out"; echo "wrote $out"; }
  fi
done
exit "$stale"
